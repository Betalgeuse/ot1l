import assert from 'node:assert/strict';
import { communityMaintenanceCron } from '../src/community-cron.ts';
import { validateMaintenanceTask, TEAM_MAINTENANCE_TASKS, CHANNEL_MAINTENANCE_TASKS } from '../src/community-maintenance-tasks.ts';
const seen=[];
const env={SLACK_TEAM_ID:'TQA',COMMUNITY_ENABLED:'true',COMMUNITY_ADMIN_ID:'UADMIN',COMMUNITY_PUBLIC_CHANNEL_ID:'CPUBLIC',COMMUNITY_CHANNEL_ID:'CPRIVATE',COMMUNITY_CLOCK:{getByName(name){return{async runMaintenanceTask(task,at,channel){seen.push({name,task,channel});assert.equal(at,123);if(task==='agent_notifications')throw Error('Too many subrequests.');}};}}};
await assert.rejects(communityMaintenanceCron(env,123),/independent tasks continued/);
assert.equal(seen.length,TEAM_MAINTENANCE_TASKS.length+2*CHANNEL_MAINTENANCE_TASKS.length);
assert.equal(new Set(seen.map(s=>s.name)).size,seen.length,'each bounded task has a separate RPC object');
assert.ok(seen.findIndex(s=>s.task==='chapter_math')>seen.findIndex(s=>s.task==='agent_notifications'),'notification quota failure cannot suppress math');
assert.equal(seen.filter(s=>s.task==='membership').length,2);
assert.equal(seen[0].task,'clock_recovery');
seen.length=0;
await communityMaintenanceCron({...env,COMMUNITY_ENABLED:'false'},123);
assert.deepEqual(seen.map(s=>s.task),['clock_recovery']);
seen.length=0;
await assert.rejects(communityMaintenanceCron({...env,COMMUNITY_CHANNEL_ID:'CPUBLIC'},123));
assert.equal(seen.filter(s=>s.task==='membership').length,1,'duplicate channel scope is not scheduled twice');
for(const args of [['arbitrary',123],['chapter_math',123,'CPUBLIC'],['membership',123,'COTHER'],['events',NaN]])assert.throws(()=>validateMaintenanceTask(env,...args));
console.log('PASS separate maintenance RPC tasks, quota failure continuation, scope validation and disabled guard');
